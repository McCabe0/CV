-- The profile, as the first version had it, owned by a keycloak user. Each user has one.
-- Lists are json arrays in text columns, not the first version's '||' packing, which broke on a '|'.
CREATE TABLE user_profiles (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id            VARCHAR(255) NOT NULL UNIQUE,
    name                VARCHAR(255) NOT NULL,
    skills              TEXT         NOT NULL,
    experience          TEXT         NOT NULL,
    education           TEXT         NOT NULL,
    target_role         VARCHAR(255),
    years_of_experience VARCHAR(255),
    location            VARCHAR(255),
    work_authorization  VARCHAR(255),
    projects            TEXT         NOT NULL,
    certifications      TEXT         NOT NULL,
    languages           TEXT         NOT NULL,
    email               VARCHAR(255),
    phone               VARCHAR(255),
    linkedin            VARCHAR(512),
    portfolio           VARCHAR(512),
    work_history_json   TEXT         NOT NULL,
    created_at          TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at          TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
