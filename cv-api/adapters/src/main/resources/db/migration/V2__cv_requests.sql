-- The interviewer's answers, kept on the profile as facts, so a later CV uses them. See decisions/agents.md.
ALTER TABLE user_profiles ADD COLUMN facts_json TEXT NOT NULL DEFAULT '[]';

-- A candidate's request for a CV, from the interviewer's questions to the finished CV. Its parts are json,
-- as they are only ever read and written whole, with their request.
CREATE TABLE cv_requests (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id       VARCHAR(255) NOT NULL,
    status         VARCHAR(32)  NOT NULL,
    questions_json TEXT         NOT NULL,
    answers_json   TEXT         NOT NULL,
    rounds_json    TEXT         NOT NULL,
    cv_json        TEXT,
    failure        TEXT,
    created_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE INDEX cv_requests_owner_id ON cv_requests (owner_id);
