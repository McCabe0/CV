-- The companies whose public job boards are crawled, and our copy of their jobs. See decisions/jobs.md.
CREATE TABLE tracked_companies (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL,
    source      VARCHAR(32)  NOT NULL,
    board_token VARCHAR(255) NOT NULL,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now(),
    -- One board is tracked once.
    UNIQUE (source, board_token)
);

CREATE TABLE jobs (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id     BIGINT       NOT NULL REFERENCES tracked_companies (id),
    source         VARCHAR(32)  NOT NULL,
    external_id    VARCHAR(255) NOT NULL,
    title          TEXT         NOT NULL,
    location       TEXT,
    description    TEXT         NOT NULL,
    apply_url      TEXT         NOT NULL,
    first_seen_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    -- Set when the board stops listing the job. An inactive job is never matched.
    inactive_since TIMESTAMP(6) WITH TIME ZONE,
    updated_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    -- A crawl upserts by the board's own id, so a posting is held once, and its index serves the crawl's read.
    UNIQUE (company_id, external_id)
);

-- Matching only ever reads active jobs.
CREATE INDEX jobs_active ON jobs (company_id) WHERE inactive_since IS NULL;
