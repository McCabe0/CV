-- The transactional outbox: a message is saved in the same transaction as the change it announces, and a
-- relay sends it to kafka after. So a crash never loses a message, nor sends one for a change that was
-- rolled back. See decisions/messaging.md.
CREATE TABLE outbox (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id    UUID         NOT NULL UNIQUE,
    topic       VARCHAR(255) NOT NULL,
    message_key VARCHAR(255) NOT NULL,
    payload     TEXT         NOT NULL,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    sent_at     TIMESTAMP(6) WITH TIME ZONE
);

-- The relay only ever looks for what is not sent yet.
CREATE INDEX outbox_unsent ON outbox (id) WHERE sent_at IS NULL;

-- The events a consumer has handled, so one that kafka delivers twice is done once.
CREATE TABLE processed_events (
    event_id     UUID PRIMARY KEY,
    processed_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
