-- Why a job fits a candidate, as the LLM wrote it, written once on asking. See decisions/jobs.md.
CREATE TABLE fit_summaries (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id   VARCHAR(255) NOT NULL,
    job_id     BIGINT       NOT NULL REFERENCES jobs (id),
    status     VARCHAR(16)  NOT NULL,
    text       TEXT,
    failure    TEXT,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    -- One per candidate and job, so two asks at once cannot both queue one; its index serves the lookup.
    UNIQUE (owner_id, job_id)
);
