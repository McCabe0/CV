-- Baseline schema for Skill2Career. Matches the JPA entities as of Milestone 1.
-- Column names follow Spring Boot's default camelCase -> snake_case naming strategy.
-- Types chosen to satisfy Hibernate `ddl-auto=validate` on PostgreSQL.

CREATE TABLE user_profiles (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(255) NOT NULL,
    skills              TEXT         NOT NULL,
    experience          TEXT         NOT NULL,
    education           TEXT         NOT NULL,
    target_role         VARCHAR(255),
    years_of_experience VARCHAR(255),
    location            VARCHAR(255),
    work_authorization  VARCHAR(255),
    projects            TEXT,
    certifications      TEXT,
    languages           TEXT,
    email               VARCHAR(255),
    phone               VARCHAR(255),
    linkedin            VARCHAR(255),
    portfolio           VARCHAR(255),
    work_history_json   TEXT,
    created_at          TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE TABLE generated_cvs (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_id  BIGINT NOT NULL REFERENCES user_profiles (id),
    summary     TEXT   NOT NULL,
    skills      TEXT   NOT NULL,
    experience  TEXT   NOT NULL,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE TABLE jobs (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_job_id VARCHAR(255) NOT NULL,
    title           VARCHAR(255) NOT NULL,
    company         VARCHAR(255) NOT NULL,
    location        VARCHAR(255) NOT NULL,
    description     TEXT         NOT NULL,
    required_skills TEXT         NOT NULL,
    role_keywords   TEXT         NOT NULL,
    source          VARCHAR(255) NOT NULL,
    created_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE TABLE job_matches (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_id              BIGINT REFERENCES user_profiles (id),
    generated_cv_id         BIGINT REFERENCES generated_cvs (id),
    job_id                  BIGINT NOT NULL REFERENCES jobs (id),
    score                   INTEGER NOT NULL,
    skill_overlap_percent   INTEGER NOT NULL,
    required_skills_missing TEXT    NOT NULL,
    confidence              INTEGER NOT NULL,
    reasoning               TEXT    NOT NULL,
    created_at              TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

-- Supports JobRepository.findFirstByExternalJobId (upsert-style dedupe on save).
CREATE INDEX idx_jobs_external_job_id ON jobs (external_job_id);
